CREATE TABLE POLLS (
    ID TEXT PRIMARY KEY NOT NULL,
    MIN_PEOPLE INTEGER NOT NULL DEFAULT 0
        CHECK (MIN_PEOPLE >= 0 AND MIN_PEOPLE = CAST(MIN_PEOPLE AS INTEGER)),
    CREATED_AT TEXT NOT NULL DEFAULT (
        STRFTIME('%Y-%m-%dT%H:%M:%fZ', 'NOW')
    )
);

CREATE TABLE POLL_PARTICIPANTS (
    POLL_ID TEXT NOT NULL,
    NAME TEXT NOT NULL CHECK (LENGTH(TRIM(NAME)) > 0),
    POSITION INTEGER NOT NULL CHECK (POSITION >= 0),

    PRIMARY KEY (POLL_ID, NAME),
    UNIQUE (POLL_ID, POSITION),
    FOREIGN KEY (POLL_ID) REFERENCES POLLS(ID) ON DELETE CASCADE
);

CREATE TABLE POLL_DATES (
    POLL_ID TEXT NOT NULL,
    POLL_DATE TEXT NOT NULL,
    POSITION INTEGER NOT NULL CHECK (POSITION >= 0),

    PRIMARY KEY (POLL_ID, POLL_DATE),
    UNIQUE (POLL_ID, POSITION),
    FOREIGN KEY (POLL_ID) REFERENCES POLLS(ID) ON DELETE CASCADE
);

CREATE TABLE POLL_RESPONSES (
    POLL_ID TEXT NOT NULL,
    PARTICIPANT_NAME TEXT NOT NULL,
    POLL_DATE TEXT NOT NULL,
    AVAILABLE INTEGER NOT NULL CHECK (AVAILABLE IN (0, 1)),

    PRIMARY KEY (POLL_ID, PARTICIPANT_NAME, POLL_DATE),
    FOREIGN KEY (POLL_ID, PARTICIPANT_NAME)
        REFERENCES POLL_PARTICIPANTS(POLL_ID, NAME) ON DELETE CASCADE,
    FOREIGN KEY (POLL_ID, POLL_DATE)
        REFERENCES POLL_DATES(POLL_ID, POLL_DATE) ON DELETE CASCADE
);
